# derive parents strictly from children (single source of truth)
for pid, m in out.items():
    for cid in m['children']:
        assert cid in out, 'unknown child ' + cid
        if pid not in out[cid]['parents']:
            out[cid]['parents'].append(pid)
# symmetric spouses
for pid, m in out.items():
    for sid in list(m['spouses']):
        assert sid in out, 'unknown spouse ' + sid
        if pid not in out[sid]['spouses']:
            out[sid]['spouses'].append(pid)

