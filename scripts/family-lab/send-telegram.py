for mid, cap in ITEMS:
    f = f"/tmp/uibuild/shots/H_{mid}.png"
    if not pathlib.Path(f).exists():
        print(mid, "MISSING FILE"); continue
    r = subprocess.run([
        "curl","-s","-m","180","-X","POST",
        f"https://api.telegram.org/bot{TOKEN}/sendDocument",
        "-F", f"chat_id={CHAT}",
        "-F", f"document=@{f}",
        "-F", f"caption={cap}",
    ], capture_output=True, text=True)
    try:
        d = json.loads(r.stdout)
        if d.get("ok"):
            print(mid, "sent msg", d["result"]["message_id"])
        else:
            print(mid, "FAIL", d.get("description"))
    except Exception as e:
        print(mid, "PARSE ERR", r.stdout[:200])
