async def render_app_video(app_tutorial, root_dir):
    from playwright.async_api import async_playwright

    app_id = app_tutorial['id']
    print(f"\n=======================================================")
    print(f"🎬 Starting rendering dedicated tutorial video for: {app_tutorial['title']}")

    output_dir = os.path.join(root_dir, f"frames_{app_id}")
    os.makedirs(output_dir, exist_ok=True)

    total_slides = len(app_tutorial['slides'])
    slide_duration = 15.0 # 15 seconds per slide * 6 slides = 90 seconds total (1.5 min)

    async with async_playwright() as p:
        browser = await p.chromium.launch()
        page = await browser.new_page(viewport={'width': 1080, 'height': 1920})

        slide_images = []
        for idx, slide in enumerate(app_tutorial['slides']):
            html_code = generate_html_slide(app_tutorial, slide, idx, total_slides, root_dir)
            await page.set_content(html_code)
            await page.wait_for_load_state('networkidle')
            await asyncio.sleep(0.3)

            img_path = os.path.join(output_dir, f"slide_{idx:02d}.png")
            await page.screenshot(path=img_path, full_page=True)
            slide_images.append(img_path)
            print(f"  [+] Slide {idx+1}/{total_slides} captured for {app_id}")

        await browser.close()

    # Generate FFmpeg MP4 Video (90 seconds)
    concat_txt = os.path.join(output_dir, "concat.txt")
    with open(concat_txt, "w", encoding="utf-8") as f:
        for s in slide_images:
            f.write(f"file '{os.path.basename(s)}'\n")
            f.write(f"duration {slide_duration}\n")
        if slide_images:
            f.write(f"file '{os.path.basename(slide_images[-1])}'\n")

    output_mp4 = os.path.abspath(f"tutorial_{app_id}.mp4")
    cmd = [
        "ffmpeg", "-y",
        "-f", "concat",
        "-safe", "0",
        "-i", concat_txt,
        "-vf", "fps=30,format=yuv420p",
        "-c:v", "libx264",
        "-preset", "medium",
        "-crf", "20",
        output_mp4
    ]

    subprocess.run(cmd, check=True, cwd=output_dir)
    print(f"✅ Video created: {output_mp4} (Duration: 90s / 1.5 minutes)")
    return output_mp4, output_dir

def send_video_to_telegram(video_path, caption, bot_token, chat_id):
    boundary = '----WebKitFormBoundary7MA4YWxkTrZu0gW'

    def encode_multipart_formdata(fields, files):
        body = bytearray()
        for key, value in fields.items():
            body.extend(f'--{boundary}\r\n'.encode('utf-8'))
            body.extend(f'Content-Disposition: form-data; name="{key}"\r\n\r\n'.encode('utf-8'))
            body.extend(f'{value}\r\n'.encode('utf-8'))
        for key, filename, content, content_type in files:
            body.extend(f'--{boundary}\r\n'.encode('utf-8'))
            body.extend(f'Content-Disposition: form-data; name="{key}"; filename="{filename}"\r\n'.encode('utf-8'))
            body.extend(f'Content-Type: {content_type}\r\n\r\n'.encode('utf-8'))
            body.extend(content)
            body.extend(b'\r\n')
        body.extend(f'--{boundary}--\r\n'.encode('utf-8'))
        return body

    with open(video_path, 'rb') as f:
        video_bytes = f.read()

    fields = {
        'chat_id': chat_id,
        'caption': caption,
        'parse_mode': 'Markdown',
        'supports_streaming': 'true'
    }
    files = [('video', os.path.basename(video_path), video_bytes, 'video/mp4')]

    data = encode_multipart_formdata(fields, files)

    url = f'https://api.telegram.org/bot{bot_token}/sendVideo'
    req = urllib.request.Request(url, data=data)
    req.add_header('Content-Type', f'multipart/form-data; boundary={boundary}')

    print(f'Sending video {os.path.basename(video_path)} to Telegram...')
    with urllib.request.urlopen(req, timeout=180) as response:
        res_body = response.read().decode('utf-8')
        res_json = json.loads(res_body)
        if res_json.get('ok'):
            print('✅ SUCCESSFULLY SENT VIDEO TO TELEGRAM CHANNEL!')
            return res_json
        else:
            print('❌ TELEGRAM RETURNED ERROR:', res_json)
            raise RuntimeError(f'Telegram upload failed: {res_json}')

